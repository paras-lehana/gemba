// Trust: what the AI may and may not do, which model answered, and the append-only audit trail of every agent and human action.
import { api, store, h, localTime } from "../core.js";

const KIND = { human: "ok", agent: "sensor", system: "idle", guardrail: "alarm" };

export async function render(main) {
  const page = h("div", { class: "page" });
  const llm = store.catalog.llm;
  page.append(h("div", { class: "page-head" }, h("div", { class: "grow" }, h("h1", {}, "Trust and audit"),
    h("p", {}, "Gemba's agents propose; people decide. Every agent step, approval, refusal and job tick is recorded here."))));
  const rules = [
    ["Agents propose, a named person approves", "Cards change nothing until someone types their name and approves."],
    ["Numbers come from tools, not the model", "Impact on every card is computed by the plant simulator; findings must cite the tool behind each fact."],
    ["A frozen sensor never sends a repair crew", "Repairs proposed on a machine with a frozen sensor are converted to a sensor check."],
    ["Parts before plans", "A repair is moved until the spare part can arrive, and a transfer is added if it is missing."],
    ["Read-only data access", "Questions run as single SELECT statements on a private copy, with file and network access off, 200-row cap, 3 s timeout."],
    ["Release needs a reading", "A machine is released only with a vibration reading at or below 2.3 mm/s after lock-out steps."],
    ["Gemini only", `Model replies from any non-Gemini model are rejected. Now: ${llm.label}${llm.models.agent ? ` (${llm.models.agent})` : ""}.`],
    ["Synthetic data", "The company, plants, customers and suppliers are fictional; part photos are AI-generated by the team."],
  ];
  page.append(h("div", { class: "grid", style: "grid-template-columns:repeat(auto-fit,minmax(260px,1fr))" },
    ...rules.map(([t, d]) => h("div", { class: "panel pad" }, h("h3", {}, "⛨ ", t), h("p", { class: "small dim", style: "margin-top:4px" }, d)))));
  const learned = h("section", { class: "panel", style: "margin-top:16px" }, h("div", { class: "panel-head" }, h("h2", {}, "What Gemba learned from your decisions"),
    h("span", { class: "right small dim" }, "passed to the Lead agent on every walk")));
  const log = h("section", { class: "panel", style: "margin-top:16px" }, h("div", { class: "panel-head" }, h("h2", {}, "Audit log")), h("div", { class: "skeleton", style: "margin:16px;height:120px" }));
  page.append(learned, log);
  main.append(page);
  const [rows, decisions] = await Promise.all([api.get("/api/audit"), api.get("/api/decisions")]);
  learned.append(decisions.length ? h("div", { class: "panel-body grid", style: "gap:6px" }, ...decisions.map((d) => h("div", { class: "small" },
    h("span", { class: `status st-${d.kind === "rejected" ? "alarm" : d.kind === "edited" ? "watch" : "ok"}` }, d.kind), " ", h("b", {}, d.title),
    d.reason ? h("span", { class: "dim" }, ` — ${d.reason}`) : null, h("span", { class: "faint" }, ` · ${d.by}`))))
    : h("p", { class: "empty" }, "No decisions yet. Approve, retime or reject a card: the next walk takes it into account."));
  log.querySelector(".skeleton").replaceWith(h("div", { class: "table-wrap" }, h("table", { class: "data" },
    h("thead", {}, h("tr", {}, h("th", {}, "Plant time"), h("th", {}, "Who"), h("th", {}, "Kind"), h("th", {}, "What"), h("th", { class: "hide-phone" }, "Detail"))),
    h("tbody", {}, ...rows.map((r) => h("tr", {}, h("td", { class: "num small" }, localTime(r.t, store.plant, true)), h("td", {}, r.actor),
      h("td", {}, h("span", { class: `status st-${KIND[r.kind] || "idle"}` }, r.kind)), h("td", {}, r.action),
      h("td", { class: "small dim hide-phone" }, r.detail, r.evidence?.length ? h("div", { class: "tiny faint" }, r.evidence.join(" · ")) : null)))))));
}
