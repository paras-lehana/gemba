// Quality station: Gemini vision inspects a part photo (sample, upload or phone camera) and marks the defect; scrap
// by machine against each machine's own normal; material lots.
import { api, h, num, money, toast, localTime, apiUrl } from "../core.js";
import { term, explain } from "../learn.js";

const DEFECT_TERM = { chatter_marks: "chatter", chatter: "chatter", porosity: "porosity" };

export async function render(main) {
  const page = h("div", { class: "page" });
  page.append(h("div", { class: "page-head" }, h("div", { class: "grow" }, h("h1", {}, "Quality station"),
    h("p", {}, "Pick a part photo or take one with your phone. Gemini looks at it, marks the defect (such as ", term("chatter", "chatter marks"), " or ", term("porosity", "porosity"), ") and names the likely cause. Below: ", term("scrap", "scrap"), " on every machine against its own normal, and the ", term("casting_lot", "casting lots"), " behind porosity."))));
  const view = h("div", { class: "inspect-view", style: "min-height:240px;display:grid;place-items:center" }, h("p", { class: "dim pad", style: "color:#cfd5e2" }, "Choose a sample or upload a photo"));
  const result = h("div", { class: "grid", style: "gap:8px" });
  const file = h("input", { type: "file", accept: "image/*", capture: "environment", hidden: true });
  const samples = h("div", { class: "samples" });
  const left = h("section", { class: "panel" }, h("div", { class: "panel-head" }, h("h2", {}, "Inspect a part"),
    h("button", { class: "btn small right", onclick: () => file.click() }, "📷 Upload or take photo")), h("div", { class: "panel-body grid" }, samples, file));
  const right = h("section", { class: "panel" }, h("div", { class: "panel-head" }, h("h2", {}, "Gemini vision result")), h("div", { class: "panel-body grid" }, view, result));
  page.append(h("div", { class: "grid", style: "grid-template-columns:repeat(auto-fit,minmax(320px,1fr))" }, left, right));
  let scrapCtx = "Scrap table: scrap % in the last 24 h, each machine's normal %, times normal, defects and cost.";
  const scrapBox = h("section", { class: "panel", style: "margin-top:16px" }, h("div", { class: "panel-head" }, h("h2", {}, "Scrap rate by machine: last 24 hours compared with each machine's normal rate")),
    h("div", { class: "scrap-explain" },
      h("p", {}, h("b", {}, "How to read this: "), term("scrap", "Scrap"), " is parts thrown away. ", h("b", {}, "Normal"), " is the machine's own usual scrap rate over past weeks. ",
        h("b", {}, "× normal"), " compares the two: 1× is a usual day, 2× or more means twice the usual waste. ", h("b", {}, "Signal"), " comes from a ", term("p_chart", "control chart"),
        ": it lights up only when the rise is too big to be everyday chance."),
      explain("Scrap rate against a machine's own normal", () => scrapCtx)),
    h("div", { class: "skeleton", style: "margin:16px;height:120px" }));
  const lotsBox = h("section", { class: "panel", style: "margin-top:16px" });
  page.append(scrapBox, lotsBox);
  main.append(page);

  async function inspect(src, body) {
    view.innerHTML = "";
    const img = h("img", { src, alt: "Part photo under inspection" });
    view.append(img, h("div", { class: "scan", "aria-hidden": "true" }));
    view.style.display = "block";
    result.replaceChildren(h("p", { class: "dim" }, "Gemini is inspecting the photo…"));
    try {
      const r = body instanceof FormData ? await api.post("/api/inspect", body) : await api.post(`/api/inspect?sample=${encodeURIComponent(body)}`, {});
      view.querySelector(".scan")?.remove();
      for (const b of r.boxes || []) {
        const [y0, x0, y1, x1] = b.box_2d;
        view.append(h("div", { class: "box", style: `top:${y0 / 10}%;left:${x0 / 10}%;width:${(x1 - x0) / 10}%;height:${(y1 - y0) / 10}%` }, h("span", {}, b.label)));
      }
      const sev = r.severity === "reject" ? "alarm" : r.severity === "minor" ? "watch" : "ok";
      result.replaceChildren(
        h("div", { class: "row gap wrap" }, h("span", { class: `status st-${sev}` }, r.severity === "ok" ? "Good part" : r.severity === "reject" ? "Reject" : "Minor"),
          h("b", {}, (r.defect || "").replace(/_/g, " ")), h("span", { class: "num dim" }, `${Math.round((r.confidence || 0) * 100)} % confident`)),
        r.part ? h("p", { class: "small dim" }, r.part) : null,
        h("p", {}, r.description),
        r.likely_cause ? h("p", { class: "small" }, h("b", {}, "Likely cause: "), r.likely_cause) : null,
        h("p", { class: "tiny faint" }, `${r.fallback ? "Rules fallback (model unavailable)" : r.model}${r.took_ms ? ` · ${(r.took_ms / 1000).toFixed(1)} s` : ""}${r.cached ? " · cached" : ""} · sample photos are AI-generated by the team`),
        r.defect === "chatter_marks" ? h("a", { class: "btn small", href: "#/machine/VMC-204" }, "Open VMC-204: chatter marks usually mean vibration") : null,
        r.defect === "porosity" ? h("a", { class: "btn small", href: "#/ask?q=" + encodeURIComponent("Which material lot is linked to porosity scrap in Rayong?") }, "Ask which lot causes porosity") : null);
    } catch (e) {
      view.querySelector(".scan")?.remove();
      result.replaceChildren(h("p", { class: "status st-alarm" }, "Inspection failed"), h("p", { class: "small" }, e.message));
    }
  }

  file.onchange = () => {
    const f = file.files[0]; if (!f) return;
    if (f.size > 6 * 1024 * 1024) { toast("Photo too large (max 6 MB).", "err"); return; }
    const fd = new FormData(); fd.append("file", f);
    inspect(URL.createObjectURL(f), fd);
    file.value = "";
  };

  const q = await api.get("/api/quality");
  for (const s of q.samples) samples.append(h("button", { class: "sample", onclick: () => inspect(apiUrl(s.url), s.name) }, h("img", { src: apiUrl(s.url), alt: s.label, loading: "lazy" }), h("span", {}, s.label)));
  const rows = q.scrap.machines;
  scrapCtx = "Scrap in the last 24 hours against each machine's normal: " + rows.slice(0, 6).map((r) => `${r.machine_id} ${r.scrap_24h_pct} % vs normal ${r.baseline_pct} % (${r.times_baseline}×${r.signal ? ", control-chart signal" : ""}), cost ${money(r.scrap_cost_24h_usd ?? r.scrap_cost_24h_inr)}`).join("; ");
  scrapBox.querySelector(".skeleton").replaceWith(h("div", { class: "table-wrap" }, h("table", { class: "data" },
    h("thead", {}, h("tr", {}, h("th", {}, "Machine"), h("th", { class: "n" }, "Scrap 24 h"), h("th", { class: "n" }, "Normal"), h("th", { class: "n" }, "× normal"), h("th", {}, "Defects (parts)"), h("th", { class: "n" }, "Cost 24 h"), h("th", {}, "Signal"))),
    h("tbody", {}, ...rows.map((r) => h("tr", { class: "click", onclick: () => (location.hash = `#/machine/${r.machine_id}`) },
      h("td", {}, h("b", {}, r.machine_id)), h("td", { class: "n" }, `${r.scrap_24h_pct} %`), h("td", { class: "n" }, `${r.baseline_pct} %`),
      h("td", { class: "n" }, r.times_baseline >= 2 ? h("span", { class: "status st-watch" }, `${r.times_baseline}×`) : `${r.times_baseline}×`),
      h("td", { class: "small" }, ...Object.entries(r.by_defect_parts).flatMap(([k, v], i) => [i ? " · " : null, DEFECT_TERM[k] ? term(DEFECT_TERM[k], k.replace(/_/g, " ")) : k.replace(/_/g, " "), ` ${num(v, 0)}`])),
      h("td", { class: "n" }, money(r.scrap_cost_24h_usd ?? r.scrap_cost_24h_inr)), h("td", {}, r.signal ? h("span", { class: "status st-watch" }, r.signal) : h("span", { class: "dim small" }, "in control"))))))));
  lotsBox.append(h("div", { class: "panel-head" }, h("h2", {}, term("casting_lot", "Casting lots"), " — Rayong gear housings")),
    h("p", { class: "scrap-explain" }, "Each lot is one batch of aluminium castings from a supplier. If one lot has ", term("porosity", "porosity"), " (gas holes), its parts fail; a ", term("quarantine", "quarantined"), " lot is set aside so nobody uses it."),
    h("div", { class: "table-wrap" }, h("table", { class: "data" }, h("thead", {}, h("tr", {}, h("th", {}, "Lot"), h("th", {}, "Supplier"), h("th", {}, "State"), h("th", { class: "n" }, "Porosity scrap"))),
      h("tbody", {}, ...q.lots.map((l) => h("tr", {}, h("td", { class: "mono" }, l.lot), h("td", {}, l.supplier),
        h("td", {}, l.quarantined ? h("span", { class: "status st-sensor" }, "quarantined") : l.in_use ? h("span", { class: "status st-watch" }, `in use ${num(l.since_hours)} h`) : l.in_stock ? "in store" : "used up"),
        h("td", { class: "n" }, l.porosity_scrap_pct != null ? `${l.porosity_scrap_pct} %` : "–")))))));
}
