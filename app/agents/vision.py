"""Gemini vision inspection of part photos: defect class, boxes, confidence and a plain explanation.

Used by the Quality station (a person uploads or takes a photo) and by the Quality agent during a walk (the latest photo
from a machine's output camera). Sample photos were generated by us with a Gemini image model (tools/make_sample_images.py).
"""
import base64
import json
import pathlib
import time

from . import llm

PARTS = pathlib.Path(__file__).resolve().parent.parent.parent / "static" / "img" / "parts"
DEFECTS = ["none", "chatter_marks", "porosity", "scratch", "dent", "burr", "crack", "tool_mark", "other"]
SCHEMA = {
    "type": "object",
    "properties": {
        "part": {"type": "string", "description": "What part this is, e.g. 'cylinder head deck face'"},
        "defect": {"type": "string", "enum": DEFECTS},
        "confidence": {"type": "number", "description": "0 to 1"},
        "severity": {"type": "string", "enum": ["ok", "minor", "reject"]},
        "boxes": {"type": "array", "items": {"type": "object", "properties": {
            "label": {"type": "string"},
            "box_2d": {"type": "array", "items": {"type": "integer"}, "description": "[ymin, xmin, ymax, xmax] scaled 0-1000"}},
            "required": ["label", "box_2d"]}},
        "description": {"type": "string", "description": "One or two sentences a quality inspector would write"},
        "likely_cause": {"type": "string", "description": "Most likely process cause (machine, tool, material)"},
    },
    "required": ["defect", "confidence", "severity", "boxes", "description", "likely_cause"],
}
PROMPT = """You are a quality inspector in an automotive machining plant. Inspect this part photo.
Classify the main surface defect (one of: {defects}). Draw a box around each defective region using box_2d =
[ymin, xmin, ymax, xmax] scaled 0-1000. If the part is good, return defect "none", severity "ok" and no boxes.
Typical causes: chatter marks come from vibration (worn spindle bearing, loose tool, wrong speed); porosity comes from
gas or shrinkage in the casting (material lot, melt temperature, shot pressure); scratches from handling.
{context}
Reply with JSON only, matching this schema: {schema}"""

_CACHE: dict = {}
SAMPLES = {"vmc204-chatter": "Cylinder head from VMC-204", "vmc201-good": "Cylinder head from VMC-201",
           "die501-porosity": "Gear housing from DIE-501", "die502-good": "Gear housing from DIE-502"}
FALLBACK = {
    "chatter_marks": {"defect": "chatter_marks", "confidence": 0.7, "severity": "reject",
                      "boxes": [{"label": "chatter marks", "box_2d": [120, 520, 820, 960]}],
                      "description": "Regular wavy ripple bands across the right side of the milled face.",
                      "likely_cause": "Vibration during face milling, typically a worn spindle bearing."},
    "porosity": {"defect": "porosity", "confidence": 0.7, "severity": "reject",
                 "boxes": [{"label": "porosity cluster", "box_2d": [380, 580, 640, 700]}],
                 "description": "A cluster of round pinholes next to the bolt hole on the sealing face.",
                 "likely_cause": "Gas porosity in the casting, often from one material lot or melt conditions."},
    "none": {"defect": "none", "confidence": 0.7, "severity": "ok", "boxes": [], "description": "Uniform machined surface, no defect.",
             "likely_cause": ""},
}


def _labels() -> dict:
    try:
        return json.loads((PARTS / "labels.json").read_text())
    except (OSError, ValueError):
        return {}


def sample_for(session, machine_id: str, now: float) -> str | None:
    """Which camera photo is 'latest' for a machine, given the visitor's plant state."""
    m = machine_id.upper()
    w = session.world
    if m == "VMC-204":
        return "vmc201-good" if w.last("repair", "VMC-204", now) and w.last("repair", "VMC-204", now).at + 4 * 3600 <= now else "vmc204-chatter"
    if m.startswith("VMC-"):
        return "vmc201-good"
    if m in ("DIE-501", "DIE-502"):
        return "die502-good" if w.last("quarantine_lot", "AL-2210", now) else "die501-porosity"
    return None


async def inspect_image(b64: str, mime: str, context: str = "") -> dict:
    """Run Gemini vision on one image. Raises llm.LLMError when no model is available."""
    msgs = [{"role": "user", "content": [
        {"type": "text", "text": PROMPT.format(defects=", ".join(DEFECTS), context=context, schema=json.dumps(SCHEMA))},
        {"type": "image", "mime": mime, "data": b64}]}]
    r = await llm.chat(msgs, role="vision", temperature=0.1, json_schema=SCHEMA)
    out = llm.parse_json(r.content)
    out["defect"] = out.get("defect") if out.get("defect") in DEFECTS else "other"
    boxes = []
    for b in out.get("boxes") or []:
        bb = b.get("box_2d") if isinstance(b, dict) else None
        if isinstance(bb, list) and len(bb) == 4 and all(isinstance(v, (int, float)) for v in bb):
            y0, x0, y1, x1 = (max(0, min(1000, int(v))) for v in bb)
            if y1 > y0 and x1 > x0:
                boxes.append({"label": str(b.get("label") or out["defect"])[:40], "box_2d": [y0, x0, y1, x1]})
    out["boxes"] = boxes[:8]
    try:
        out["confidence"] = max(0.0, min(1.0, float(out.get("confidence", 0.5))))
    except (TypeError, ValueError):
        out["confidence"] = 0.5
    out.update(model=r.model, provider=r.provider, took_ms=r.ms, fallback=False)
    return out


async def inspect_sample(name: str, context: str = "") -> dict:
    hit = _CACHE.get(name)
    if hit and time.time() - hit[0] < 600:
        return {**hit[1], "cached": True}
    b64 = base64.b64encode((PARTS / f"{name}.jpg").read_bytes()).decode()
    try:
        res = await inspect_image(b64, "image/jpeg", context)
    except (llm.LLMError, ValueError, KeyError) as e:
        truth = _labels().get(name, {}).get("truth", "none")
        res = {**FALLBACK.get(truth, FALLBACK["none"]), "model": "rules engine", "fallback": True, "error": str(e)[:160]}
    res["image_url"] = f"/static/img/parts/{name}.jpg"
    res["sample"] = name
    if not res.get("fallback"):
        _CACHE[name] = (time.time(), res)
    return res


async def inspect_for_agent(session, now: float, machine_id: str):
    t = time.time()
    name = sample_for(session, machine_id or "", now)
    if not name:
        return {"error": f"no output camera on {machine_id}; cameras are on the VMC cells and the die-casting cells"}, \
            "no camera on this machine", 0
    res = await inspect_sample(name, f"The part comes from machine {machine_id.upper()}.")
    session.inspections.append({"t": now, "machine_id": machine_id.upper(), "by": "Quality agent", **{k: res.get(k) for k in (
        "defect", "confidence", "severity", "image_url", "model", "fallback")}})
    summ = f"{res['defect'].replace('_', ' ')} ({res['confidence']:.0%})" + (" · rules fallback" if res.get("fallback") else "")
    out = {k: res.get(k) for k in ("part", "defect", "confidence", "severity", "boxes", "description", "likely_cause", "model", "image_url")}
    out["machine_id"] = machine_id.upper()
    return out, summ, int(1000 * (time.time() - t))
